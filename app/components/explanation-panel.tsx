import type { Explanation } from "../lib/types";

/**
 * The plain-English explanation shown beside the verdict. Labelled honestly:
 * "AI explanation" only for a model answer that passed validation, otherwise
 * "Built-in explanation" with the reason. Rendered as plain text.
 */
export function ExplanationPanel({ explanation }: { explanation: Explanation }) {
  const ai = explanation.source === "ai";
  return (
    <section aria-labelledby="explanation-heading" className="rounded-xl border border-border bg-card p-4 sm:p-5">
      <div className="flex flex-wrap items-baseline justify-between gap-x-3 gap-y-1">
        <h2 id="explanation-heading" className="text-sm font-semibold">
          {ai ? "AI explanation" : "Built-in explanation"}
        </h2>
        {ai && explanation.model && (
          <span className="text-xs text-muted">
            model {explanation.model}
            {explanation.reused ? ", reused for the same findings" : ""}
          </span>
        )}
      </div>
      <p className="mt-2 text-sm leading-relaxed break-words">{explanation.summary}</p>
      {explanation.points.length > 0 && (
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm break-words">
          {explanation.points.map((point, i) => (
            <li key={i}>{point}</li>
          ))}
        </ul>
      )}
      <p className="mt-3 text-sm font-semibold break-words">{explanation.advice}</p>
      <p className="mt-3 text-xs text-muted">
        {ai
          ? "Written by AI from the findings below. It cannot change the verdict, which comes from fixed rules."
          : `${explanation.notice ? `${explanation.notice.message} ` : ""}This text is generated by SignSafe from the same findings.`}
      </p>
    </section>
  );
}
